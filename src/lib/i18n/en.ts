/**
 * English dictionary — and, by inference, the shape every other locale must satisfy.
 *
 * `Dict` is derived from this object with `typeof`, so a missing or misspelled key in
 * another locale is a compile error rather than a string that silently falls back to
 * English at runtime.
 *
 * Entries are functions wherever grammar depends on the values. Templating with
 * placeholders alone does not survive translation: French needs agreement, elision
 * ("de" vs "d'"), and different plural rules, and those decisions belong in the locale
 * file rather than at the call site.
 */
