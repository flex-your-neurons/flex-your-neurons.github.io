/** 「1、2 と 3」— 日本語の列挙。 */
function jaList(items: string[], conjunction: string): string {
  if (items.length === 0) return '';
  if (items.length === 1) return items[0]!;
  return `${items.slice(0, -1).join('、')}${conjunction}${items[items.length - 1]}`;
}

/** Signed millisecond figure: "+120 ミリ秒", "−40 ミリ秒". */
function jaSignedMs(n: number): string {
  return `${n > 0 ? '+' : ''}${n} ミリ秒`;
}

/** 「A、B、C」— Japanese list, joined with the full-width comma. */
function jaJoin(parts: string[]): string {
  return parts.join('、');
}

/** "+3" / "-2" — a signed step, as the letter-series explanations print it. */
function jaSigned(n: number): string {
  return n > 0 ? `+${n}` : `${n}`;
}

